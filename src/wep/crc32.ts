/**
 * CRC-32 — the reflected IEEE convention, hand-rolled.
 *
 * Hand-rolled for the same reason as RC4: it is a teaching subject here, not a
 * utility. The whole of panel 4 turns on one algebraic property of this
 * function, so a reader has to be able to open the file and check it.
 *
 * Parameters (brief section 4; RFC 1952 section 8 [R5] is the independent
 * reference for the routine and its initialisation/finalisation convention):
 *   - normal polynomial 0x04C11DB7, reflected representation 0xEDB88320
 *   - initial register 0xFFFFFFFF
 *   - reflected (LSB-first) processing
 *   - final XOR 0xFFFFFFFF
 * Check values: CRC32("123456789") = 0xCBF43926; CRC32("") = 0.
 *
 * THIS IS NOT THE 802.11 FCS. WEP's ICV is a CRC-32 of the plaintext payload,
 * encrypted along with it. The outer frame check sequence is a separate field
 * on a real radio frame and is outside this lab's model entirely (brief
 * section 3).
 */

/** The reflected representation of the IEEE polynomial 0x04C11DB7. */
export const CRC32_POLY_REFLECTED = 0xedb88320;
/** The normal (unreflected) representation, recorded for the reader. */
export const CRC32_POLY_NORMAL = 0x04c11db7;
export const CRC32_INIT = 0xffffffff;
export const CRC32_FINAL_XOR = 0xffffffff;

/** The byte-at-a-time table, derived from the reflected polynomial. */
const TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? CRC32_POLY_REFLECTED ^ (c >>> 1) : c >>> 1;
    }
    t[n] = c >>> 0;
  }
  return t;
})();

/** CRC-32 of `data`, initialised and finalised. */
export function crc32(data: Uint8Array): number {
  let c = CRC32_INIT;
  for (let i = 0; i < data.length; i++) {
    c = TABLE[(c ^ data[i]) & 0xff] ^ (c >>> 8);
  }
  return (c ^ CRC32_FINAL_XOR) >>> 0;
}

/**
 * The same CRC computed bit-at-a-time with no lookup table.
 *
 * An INDEPENDENT route to the same answer, which is what the brief's
 * "verify the routine against an independent reference" asks for: the table
 * above is generated by this lab, so a table-vs-table check would only prove
 * the lab agrees with itself. `crc32.test.ts` asserts the two agree over many
 * inputs AND that both hit the published check values.
 */
export function crc32Bitwise(data: Uint8Array): number {
  let c = CRC32_INIT;
  for (let i = 0; i < data.length; i++) {
    c = (c ^ data[i]) >>> 0;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? (CRC32_POLY_REFLECTED ^ (c >>> 1)) >>> 0 : c >>> 1;
    }
  }
  return (c ^ CRC32_FINAL_XOR) >>> 0;
}

/** A 32-bit value serialised little-endian — the WEP ICV byte order. */
export function le32(value: number): Uint8Array {
  const v = value >>> 0;
  return new Uint8Array([v & 0xff, (v >>> 8) & 0xff, (v >>> 16) & 0xff, (v >>> 24) & 0xff]);
}

/** A little-endian 4-byte field read back as a 32-bit value. */
export function readLe32(bytes: Uint8Array, at = 0): number {
  return (
    (bytes[at] | (bytes[at + 1] << 8) | (bytes[at + 2] << 16) | (bytes[at + 3] << 24)) >>> 0
  );
}

/**
 * The ICV correction term for an XOR modification — the whole of panel 4.
 *
 * The initialised/finalised CRC above is AFFINE at a fixed length, so its XOR
 * difference is linear. For an n-byte payload P and an n-byte XOR mask D:
 *
 *   CRC32(P XOR D) XOR CRC32(P) = CRC32(D) XOR CRC32(zeros(n))
 *
 * The `CRC32(zeros(n))` term is what cancels the fixed initialisation and
 * finalisation offset, and it is NOT optional: a bare `CRC32(D)` is the wrong
 * correction for this CRC API, and using it is one of the mutations in
 * `scripts/mutations.mjs`.
 *
 * The attacker computes this from D ALONE — no plaintext, no key. That is the
 * property that makes a WEP ICV useless as an authenticity check.
 */
export function icvDelta(mask: Uint8Array): number {
  return (crc32(mask) ^ crc32(new Uint8Array(mask.length))) >>> 0;
}
